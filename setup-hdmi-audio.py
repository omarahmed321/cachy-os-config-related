#!/usr/bin/env python3
# =============================================================================
#   HDMI / DisplayPort Audio Output Selector (NVIDIA multi-display aware)
#   Part of: CachyOS + HyDE System Restorer
#   Repo:    https://github.com/omarahmed321/cachy-os-config-related
#
#   A GPU with several HDMI/DP screens exposes one ALSA card whose profile picks
#   which screen gets sound (output:hdmi-stereo, output:hdmi-stereo-extra1, ...).
#   This lists those outputs with the monitor plugged into each, switches the
#   card profile, makes the new sink the default and pins the choice with a
#   WirePlumber rule so it survives reboots.
#
#   Usage:
#     setup-hdmi-audio.py              pick an output interactively
#     setup-hdmi-audio.py --auto       use the output feeding the primary monitor
#     setup-hdmi-audio.py --list       only show outputs
#     setup-hdmi-audio.py --profile output:hdmi-stereo-extra1 [--card NAME]
# =============================================================================

import argparse
import glob
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys

WP_RULE = os.path.expanduser("~/.config/wireplumber/wireplumber.conf.d/51-hdmi-audio-profile.conf")


def pactl_json(*args):
    out = subprocess.run(["pactl", "-f", "json", *args], capture_output=True, text=True)
    if out.returncode != 0:
        raise RuntimeError(out.stderr.strip() or "pactl failed")
    return json.loads(out.stdout)


def eld_names(alsa_card):
    """Monitor names the GPU read from each HDMI/DP sink's ELD, in device order."""
    names = []
    for path in sorted(glob.glob(f"/proc/asound/card{alsa_card}/eld#*"),
                       key=lambda p: [int(x) for x in re.findall(r"\d+", os.path.basename(p))]):
        name = ""
        try:
            with open(path) as f:
                for line in f:
                    if line.startswith("monitor_name"):
                        name = line.split(None, 1)[1].strip() if len(line.split(None, 1)) > 1 else ""
        except OSError:
            pass
        names.append(name)
    return names


def hdmi_outputs():
    outputs = []
    for card in pactl_json("list", "cards"):
        profiles = card.get("profiles", {})
        props = card.get("properties", {})
        elds = eld_names(props.get("alsa.card", "x"))
        for port_name, port in card.get("ports", {}).items():
            if "hdmi" not in port_name and "displayport" not in port_name.lower():
                continue
            if port.get("direction", "output") not in ("output", "Output"):
                continue
            stereo = [p for p in port.get("profiles", []) if p.startswith("output:hdmi-stereo")]
            if not stereo:
                continue
            profile = min(stereo, key=len)  # plain stereo, not the +input combo profiles
            idx = re.search(r"(\d+)$", port_name)
            monitor = (port.get("properties", {}).get("device.product.name")
                       or (elds[int(idx.group(1))] if idx and int(idx.group(1)) < len(elds) else ""))
            available = str(port.get("availability", "")).lower() in ("available", "yes", "unknown")
            outputs.append({
                "card": card["name"],
                "card_desc": props.get("device.description", card["name"]),
                "port": port_name, "profile": profile, "monitor": monitor or "(no monitor info)",
                "available": available and profiles.get(profile, {}).get("available", True),
                "active": card.get("active_profile") == profile,
            })
    return outputs


def primary_monitor_model():
    """EDID model name of the primary screen saved by hypr-monitor-setup.py."""
    here = os.path.dirname(os.path.abspath(__file__))
    engine = next((p for p in (os.path.join(here, "hypr-monitor-setup.py"),
                               os.path.expanduser("~/.local/share/bin/hypr-monitor-setup.py"))
                   if os.path.isfile(p)), None)
    if not engine:
        return ""
    spec = importlib.util.spec_from_file_location("hypr_monitor_setup", engine)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    primary = mod.load_state().get("primary")
    return mod.read_edid(primary)["name"] if primary else ""


def write_wireplumber_rule(card, profile):
    os.makedirs(os.path.dirname(WP_RULE), exist_ok=True)
    with open(WP_RULE, "w") as f:
        f.write(f"""# Generated by setup-hdmi-audio.py: keep sound on the chosen HDMI/DP screen
monitor.alsa.rules = [
  {{
    matches = [ {{ device.name = "{card}" }} ]
    actions = {{ update-props = {{ device.profile = "{profile}" }} }}
  }}
]
""")


def apply(output):
    subprocess.run(["pactl", "set-card-profile", output["card"], output["profile"]], check=True)
    for sink in pactl_json("list", "sinks"):
        props = sink.get("properties", {})
        if props.get("device.name") == output["card"] and \
                props.get("device.profile.name") == output["profile"].split(":", 1)[1]:
            subprocess.run(["pactl", "set-default-sink", sink["name"]], check=False)
            break
    write_wireplumber_rule(output["card"], output["profile"])
    print(f"Sound now goes to {output['monitor']} ({output['profile']} on {output['card_desc']}).")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--auto", action="store_true")
    p.add_argument("--list", action="store_true")
    p.add_argument("--profile")
    p.add_argument("--card")
    args = p.parse_args()

    if not shutil.which("pactl"):
        print("pactl not found (install libpulse / pipewire-pulse).", file=sys.stderr)
        return 1
    try:
        outputs = hdmi_outputs()
    except (RuntimeError, ValueError) as e:
        print(f"Could not read audio cards: {e}", file=sys.stderr)
        return 1
    if not outputs:
        print("No HDMI/DisplayPort audio outputs found.")
        return 0

    for i, o in enumerate(outputs, 1):
        flags = (" [active]" if o["active"] else "") + ("" if o["available"] else " [nothing plugged in]")
        print(f"  {i}) {o['monitor']:<24} {o['profile']:<28} {o['card_desc']}{flags}")
    if args.list:
        return 0

    choice = None
    if args.profile:
        choice = next((o for o in outputs if o["profile"] == args.profile
                       and (not args.card or o["card"] == args.card)), None)
    elif args.auto:
        model = primary_monitor_model().lower()
        if model:
            choice = next((o for o in outputs if model in o["monitor"].lower()), None)
        if not choice:
            print("Could not match the primary monitor to an audio output; leaving audio as is.")
            return 0
    else:
        try:
            with open("/dev/tty", "w") as out, open("/dev/tty") as inp:
                out.write("Send sound to which output? [number, Enter = keep]: ")
                out.flush()
                ans = inp.readline().strip()
        except OSError:
            ans = ""
        if ans.isdigit() and 1 <= int(ans) <= len(outputs):
            choice = outputs[int(ans) - 1]
    if not choice:
        return 0
    apply(choice)
    return 0


if __name__ == "__main__":
    sys.exit(main())
